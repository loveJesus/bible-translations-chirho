    WHERE pw.word_id = '2000501301' AND p.language_id = (SELECT id FROM language WHERE code = 'ben') AND p.deleted_at IS NULL
  )
  RETURNING id
)
INSERT INTO phrase_word (phrase_id, word_id) SELECT id, '2000501301' FROM np ON CONFLICT DO NOTHING;
