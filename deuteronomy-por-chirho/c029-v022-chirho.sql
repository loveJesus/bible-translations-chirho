    SELECT 1 FROM phrase p JOIN phrase_word pw ON pw.phrase_id = p.id
    WHERE pw.word_id = '0502902223' AND p.language_id = (SELECT id FROM language WHERE code = 'por') AND p.deleted_at IS NULL
