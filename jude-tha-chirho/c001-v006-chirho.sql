WHERE pw.word_id = '6500100622' AND p.language_id = (SELECT id FROM language WHERE code = 'tha') AND p.deleted_at IS NULL
ON CONFLICT (phrase_id) DO UPDATE SET gloss = EXCLUDED.gloss, updated_at = EXCLUDED.updated_at, source = EXCLUDED.source;
COMMIT;
