    WHERE pw.word_id = '2800700401' AND p.language_id = (SELECT id FROM language WHERE code = 'tur') AND p.deleted_at IS NULL
  )
  RETURNING id
)
INSERT INTO phrase_word (phrase_id, word_id) SELECT id, '2800700401' FROM np ON CONFLICT DO NOTHING;
