    WHERE pw.word_id = '0202802001' AND p.language_id = (SELECT id FROM language WHERE code = 'kor') AND p.deleted_at IS NULL
  )
  RETURNING id
)
INSERT INTO phrase_word (phrase_id, word_id) SELECT id, '0202802001' FROM np ON CONFLICT DO NOTHING;
