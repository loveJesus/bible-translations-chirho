    WHERE pw.word_id = '0901800621' AND p.language_id = (SELECT id FROM language WHERE code = 'tam') AND p.deleted_at IS NULL
  )
  RETURNING id
)
INSERT INTO phrase_word (phrase_id, word_id) SELECT id, '0901800621' FROM np ON CONFLICT DO NOTHING;
