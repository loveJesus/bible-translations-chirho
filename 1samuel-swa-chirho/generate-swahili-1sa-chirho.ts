const allWordsChirho = JSON.parse(wordsFileChirho);

// Create translations for all words
const glossesChirho: Record<string, string> = {};

// Process each word
for (const [wordIdChirho, hebrewTextChirho] of Object.entries(allWordsChirho)) {
  const cleanHebrewChirho = (hebrewTextChirho as string).replace(/[\u0591-\u05C7]/g, ''); // Remove cantillation

  // First try exact match
  if (hebrewToSwahiliChirho[hebrewTextChirho as string]) {
    glossesChirho[wordIdChirho] = hebrewToSwahiliChirho[hebrewTextChirho as string];
  }
  // Then try clean match
  else if (hebrewToSwahiliChirho[cleanHebrewChirho]) {
    glossesChirho[wordIdChirho] = hebrewToSwahiliChirho[cleanHebrewChirho];
  }
  // Mark as needing translation
  else {
    glossesChirho[wordIdChirho] = `[${cleanHebrewChirho}]`;
  }
}

// Count coverage
